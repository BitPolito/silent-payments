import { test, expect } from '@playwright/test'

test('investigate reuse, reveal evidence, compare silent outputs, and reset', async ({ page }) => {
  await page.goto('/?view=privacy')
  await page.locator('#observer > summary').click()
  const challenge = page.getByRole('region', { name: 'Can you find Bob?' })
  const cards = challenge.locator('.sp-evidence-card')
  await expect(cards).toHaveCount(8)
  await expect(challenge.getByText('Bob’s payment', { exact: false })).toHaveCount(0)
  for (const card of await cards.all()) if (await card.locator('.sp-evidence-key').textContent() === 'BOB-A') await card.click()
  await expect(challenge.getByRole('status')).toHaveText('3 selected · 3 belong to Bob')
  await challenge.getByRole('button', { name: 'Reveal wallet matches' }).click()
  const result = challenge.getByRole('region', { name: 'Your hypothesis vs. the simulated wallet' })
  await expect(result).toBeFocused()
  await expect(result.locator('dd')).toHaveText(['3', '0', '0'])
  await expect(cards.first()).toBeDisabled()
  await challenge.getByRole('button', { name: 'Silent output keys', exact: true }).click()
  await expect(result).toHaveCount(0)
  await expect(challenge.locator('[aria-pressed=true].sp-evidence-card')).toHaveCount(0)
  expect(new Set(await cards.locator('.sp-evidence-key').allTextContents()).size).toBe(8)
  await challenge.getByLabel('Reveal a public receipt').check()
  const receipt = challenge.getByRole('status').filter({ hasText: 'Bob posted' })
  const id = (await receipt.textContent()).match(/#(\d+)/)[1]
  await challenge.getByRole('button', { name: `Suspect output ${id}`, exact: true }).click()
  await challenge.getByRole('button', { name: 'Reveal wallet matches' }).click()
  await expect(result.locator('dd')).toHaveText(['1', '2', '0'])
  await challenge.getByRole('button', { name: 'Deal a new board' }).click()
  await expect(challenge.getByLabel('Reveal a public receipt')).not.toBeChecked()
  await expect(result).toHaveCount(0)
  await expect(cards).toHaveCount(8)
  await challenge.getByRole('button', { name: 'Reveal wallet matches' }).click()
  await expect(result.locator('dd')).toHaveText(['0', '3', '0'])
  await page.getByRole('button', { name: 'Start again' }).click()
  await expect(challenge.getByRole('region')).toHaveCount(0)
})

test('Italian challenge is keyboard accessible on a narrow dark screen without the API', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 900 })
  await page.addInitScript(() => { localStorage.setItem('sp-locale', 'it'); localStorage.setItem('theme', 'dark') })
  await page.route('**/api/**', (route) => route.abort())
  await page.goto('/?view=privacy')
  await page.locator('#observer > summary').click()
  const challenge = page.getByRole('region', { name: 'Riesci a trovare Bob?' })
  const card = challenge.getByRole('button', { name: 'Seleziona output sospetto 1', exact: true })
  await card.focus()
  await page.keyboard.press('Space')
  await expect(card).toHaveAttribute('aria-pressed', 'true')
  await challenge.getByRole('button', { name: 'Rivela i risultati del wallet' }).click()
  await expect(challenge.getByRole('region')).toBeFocused()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
