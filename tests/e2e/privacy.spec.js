import { test, expect } from '@playwright/test'

test('compare reuse, fresh addresses and Silent Payments without hiding amounts', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('link', { name: 'Explore address reuse' }).click()
  await expect(page).toHaveURL(/view=privacy/)
  await expect(page.getByRole('heading', { level: 1 })).toBeFocused()
  const rows = page.locator('.sp-lab-payment')
  await expect(rows).toHaveCount(2)
  await page.getByRole('button', { name: 'Add a payment' }).click()
  await expect(rows).toHaveCount(3)
  await expect(page.locator('.sp-lab-payment[data-linked]')).toHaveCount(3)
  const amounts = await rows.locator('strong').allTextContents()
  await page.getByRole('button', { name: 'Fresh addresses', exact: true }).click()
  await expect(page.locator('.sp-lab-payment[data-linked]')).toHaveCount(1)
  await page.getByRole('button', { name: 'Inspect payment 3', exact: true }).click()
  await expect(rows.nth(2)).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Silent Payments', exact: true }).click()
  await expect(page.locator('.sp-lab-payment[data-linked]')).toHaveCount(1)
  expect((await rows.locator('strong').allTextContents()).filter((_, i) => i % 2)).toEqual(amounts.filter((_, i) => i % 2))
  await page.getByRole('button', { name: 'Bob’s wallet', exact: true }).click()
  await expect(page.getByText('Not scanned yet', { exact: true })).toHaveCount(3)
  await page.getByRole('button', { name: 'Simulate Bob’s scan' }).click()
  await expect(page.getByText('✓ Recognized by Bob', { exact: true })).toHaveCount(3)
  await page.getByRole('button', { name: 'Add a payment' }).click()
  await expect(page.getByText('Not scanned yet', { exact: true })).toHaveCount(1)
  await page.getByRole('button', { name: 'Outside observer', exact: true }).click()
  await expect(page.getByText('✓ Recognized by Bob', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'No, the address alone is not enough' }).click()
  await expect(page.getByText(/^Exactly\./)).toBeVisible()
  await page.getByRole('button', { name: 'Start again' }).click()
  await expect(rows).toHaveCount(2)
  await expect(page.getByText(/^Exactly\./)).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Reuse an address', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('link', { name: 'See how the protocol does it' }).click()
  await expect(page.getByTestId('stage-teaching')).toBeVisible()
})

for (const [locale, dark] of [['en', false], ['it', true]]) {
  test(`privacy lab supports ${locale} on a narrow screen and works without the API`, async ({ page }) => {
    await page.setViewportSize({ width: 320, height: 900 })
    await page.addInitScript(({ locale, dark }) => { localStorage.setItem('sp-locale', locale); localStorage.setItem('theme', dark ? 'dark' : 'light') }, { locale, dark })
    await page.route('**/api/**', (route) => route.abort())
    await page.goto('/?view=privacy&campaign=learn')
    await expect(page.getByRole('heading', { level: 1 })).toHaveText(locale === 'en' ? 'Privacy lab' : 'Laboratorio privacy')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    const add = page.getByRole('button', { name: locale === 'en' ? 'Add a payment' : 'Aggiungi un pagamento' })
    for (let i = 0; i < 4; i++) await add.click()
    await expect(add).toBeDisabled()
    const silent = page.getByRole('button', { name: 'Silent Payments', exact: true })
    await silent.focus()
    await page.keyboard.press('Enter')
    await expect(silent).toHaveAttribute('aria-pressed', 'true')
    await page.getByRole('button', { name: locale === 'en' ? 'Yes, because it is public' : 'Sì, perché è pubblico' }).click()
    await expect(page.getByText(locale === 'en' ? /^Try the observer view again/ : /^Riprova la vista/)).toBeVisible()
    await page.getByRole('link', { name: locale === 'en' ? /Back to home/ : /Torna alla home/ }).click()
    await expect(page).toHaveURL(/\?campaign=learn$/)
    await page.goBack()
    await expect(page.locator('.sp-lab-payment')).toHaveCount(2)
  })
}
