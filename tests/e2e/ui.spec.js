import { test, expect } from '@playwright/test'

async function noHorizontalOverflow(page) {
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
}

test('learning uses pages and browser Back/Forward retains reference selection', async ({ page }) => {
  await page.goto('/?campaign=learn')
  await page.getByRole('link', { name: /^Guided demo/ }).click()
  await expect(page).toHaveURL(/view=walkthrough/)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('heading', { level: 1, name: 'Guided demo' })).toBeFocused()
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(page.getByRole('region', { name: '2 Alice', exact: true })).toBeFocused()
  await page.getByRole('link', { name: 'All reference cases', exact: true }).click()
  await page.getByLabel('Reference case', { exact: true }).selectOption('18')
  await page.getByLabel('Direction', { exact: true }).selectOption('receive')
  await page.getByLabel('Subcase', { exact: true }).selectOption('1')
  await page.goBack()
  await expect(page.getByRole('heading', { level: 1, name: 'Guided demo' })).toBeVisible()
  await page.goForward()
  await expect(page.getByLabel('Reference case', { exact: true })).toHaveValue('18')
  await expect(page.getByLabel('Subcase', { exact: true })).toHaveValue('1')
  await expect(page.getByTestId('reference-result')).toHaveCount(0)
  await page.getByRole('link', { name: /Back to home/ }).click()
  expect(new URL(page.url()).search).toBe('?campaign=learn')
})

test('the generator contains focus, supports Escape, and restores the opener', async ({ page }) => {
  await page.goto('/')
  const opener = page.getByRole('button', { name: /^Generate address/ })
  await opener.click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole('heading', { level: 2 })).toBeFocused()
  await expect(dialog.getByRole('radio', { name: /^Testnet/ })).toBeChecked()
  const close = dialog.getByRole('button', { name: 'Close', exact: true })
  const last = dialog.getByRole('button', { name: 'Generate', exact: true })
  await close.focus()
  await page.keyboard.press('Shift+Tab')
  await expect(last).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(close).toBeFocused()
  await page.locator('header a').first().evaluate((element) => element.focus())
  expect(await page.evaluate(() => Boolean(document.activeElement.closest('dialog')))).toBe(true)
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(opener).toBeFocused()
  expect(await page.evaluate(() => document.body.style.overflow)).toBe('')
})

test('the key notice is outside mode buttons and a network change clears previous results', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: /^Generate address/ }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.getByRole('group', { name: 'Generation mode' })).not.toContainText('server generates')
  await expect(dialog.getByText(/The server generates and sees/)).toBeVisible()
  await dialog.getByRole('button', { name: 'Generate', exact: true }).click()
  await expect(dialog.getByRole('button', { name: /Backup \(PDF\)/ })).toBeVisible()
  await expect(dialog.getByRole('heading', { name: 'Address', exact: true })).toBeFocused()
  await dialog.getByRole('radio', { name: /^Mainnet/ }).check()
  await expect(dialog.getByRole('button', { name: /Backup \(PDF\)/ })).toHaveCount(0)
  await expect(dialog.getByRole('button', { name: 'Generate', exact: true })).toBeEnabled()
})

for (const [width, locale, dark] of [[320, 'en', false], [390, 'it', true], [1280, 'en', false], [1280, 'it', true]]) {
  test(`layouts fit at ${width}px in ${locale}, ${dark ? 'dark' : 'light'} theme`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    await page.addInitScript(({ locale, dark }) => { localStorage.setItem('sp-locale', locale); localStorage.setItem('theme', dark ? 'dark' : 'light') }, { locale, dark })
    await page.goto('/')
    await noHorizontalOverflow(page)
    await page.getByRole('link', { name: locale === 'en' ? /^Guided demo/ : /^Demo guidata/ }).click()
    await expect(page.getByTestId('stage-teaching')).toBeVisible()
    await noHorizontalOverflow(page)
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await expect(page.getByRole('button', { name: locale === 'en' ? 'Continue' : 'Continua', exact: true })).toBeInViewport()
    await page.getByRole('link', { name: locale === 'en' ? 'All reference cases' : 'Tutti i casi di riferimento', exact: true }).click()
    await expect(page.getByTestId('reference-lesson')).toBeVisible()
    await noHorizontalOverflow(page)
    await page.getByRole('link', { name: locale === 'en' ? /Back to home/ : /Torna alla home/ }).click()
    await page.getByRole('button', { name: locale === 'en' ? /^Generate address/ : /^Genera indirizzo/ }).click()
    await expect(page.getByRole('dialog')).toBeVisible()
    await noHorizontalOverflow(page)
    const bounds = await page.getByRole('dialog').boundingBox()
    expect(bounds.x).toBeGreaterThanOrEqual(0)
    expect(bounds.x + bounds.width).toBeLessThanOrEqual(width)
  })
}

test('skip link reaches main content and reduced motion is respected', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await page.getByRole('link', { name: 'Skip to content' }).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('main')).toBeFocused()
  const motion = await page.getByRole('link', { name: /^Guided demo/ }).evaluate((element) => getComputedStyle(element).transitionDuration)
  expect(motion.split(',').every((duration) => parseFloat(duration) < 0.01)).toBe(true)
})
