import { test, expect } from '@playwright/test'
test('coins and scenarios are interactive cards; payment values stay in technical details', async ({ page }) => {
  await page.goto('/?view=studio&tool=payment')
  await expect(page.getByRole('checkbox', { name: 'Coin 1', exact: true })).toBeChecked()
  await page.getByRole('checkbox', { name: 'Coin 3', exact: true }).check()
  await expect(page.locator('.sp-mini-coins i')).toHaveCount(3)
  await page.getByRole('button', { name: 'Make a payment', exact: true }).click()
  await expect(page.getByText('✓ Real result')).toBeVisible()
  await expect(page.locator('.sp-friendly-stage code:visible')).toHaveCount(0)
  const payment = page.getByRole('button', { name: 'Open payment card 1', exact: true }).first()
  await payment.click()
  await expect(payment).toHaveAttribute('aria-expanded','true')
  await expect(page.getByText('A fresh destination for this payment. The full value is in the details.')).toBeVisible()
  await page.getByRole('button', { name: 'Shuffle the coins', exact: true }).click()
  await expect(page.getByText('✓ Real result')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Shuffle the coins', exact: true })).toHaveAttribute('aria-pressed','true')
})
test('transaction cards reveal plain-language explanations from actual results', async ({ page }) => {
  await page.goto('/?view=studio&tool=scan')
  await expect(page.locator('.sp-transaction-card')).toHaveCount(6)
  await page.getByRole('button', { name: 'Open the wallet', exact: true }).click()
  const rejected = page.getByTestId('transaction-malformed_witness')
  await rejected.getByRole('button').click()
  await expect(rejected).toContainText('The example contains incomplete data. The wallet rejected it.')
  await expect(rejected.getByRole('button')).toHaveAttribute('aria-expanded','true')
})
