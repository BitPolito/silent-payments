import { test, expect } from '@playwright/test'

test('real payment outputs, discovery and independent signature evidence', async ({ page }) => {
  await page.goto('/?view=studio&tool=payment&preset=default')
  await page.getByRole('button', { name: 'Two payments', exact: true }).click()
  await page.getByRole('button', { name: 'Make a payment', exact: true }).click()
  await expect(page.getByText('New coin. New destination.', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Find Bob’s payment', exact: true }).click()
  await expect(page.getByText('Original: 2 → After change: 2')).toBeVisible()
  await page.getByRole('button', { name: 'Check ownership', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Bob can spend the original payments' })).toBeVisible()
  await page.getByRole('button', { name: 'Swap coins afterward', exact: true }).click()
  await expect(page.getByText('Bob can spend the original payments')).toHaveCount(0)
  await page.getByRole('button', { name: 'Make a payment', exact: true }).click()
  await page.getByRole('button', { name: 'Find Bob’s payment', exact: true }).click()
  await expect(page.getByText('Original: 2 → After change: 0')).toBeVisible()
  await page.getByRole('button', { name: 'Shuffle the coins', exact: true }).click()
  await page.getByRole('button', { name: 'Make a payment', exact: true }).click()
  await expect(page.getByText('Same destination. Different experiment.', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Change the amount', exact: true }).click()
  await page.getByRole('button', { name: 'Make a payment', exact: true }).click()
  await expect(page.locator('.sp-payment-amount')).toHaveText(['12,000 sats','12,001 sats'])
  await expect(page.getByText('Same destination. Different experiment.', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Reset', exact: true }).click()
  await expect(page.getByText('✓ Real result', { exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Swap a coin', exact: true })).toHaveAttribute('aria-pressed','true')
})

test('inspect both networks, versions and checksum errors without sharing an entered address', async ({ page }) => {
  await page.goto('/?view=studio&tool=address')
  await page.getByRole('button', { name: 'Try an example' }).click()
  const sample = await page.getByLabel('Public Silent Payments address', { exact: true }).inputValue()
  expect(sample).toMatch(/^tsp1/)
  await page.getByRole('button', { name: 'Check this address' }).click()
  await expect(page.getByText('This address checks out')).toBeVisible()
  await page.getByText('Network & advanced settings', { exact: true }).click()
  await page.getByLabel('Network', { exact: true }).selectOption('mainnet')
  await page.getByRole('button', { name: 'Try an example' }).click()
  const mainnet = await page.getByLabel('Public Silent Payments address', { exact: true }).inputValue()
  expect(mainnet).toMatch(/^sp1/)
  await page.getByRole('button', { name: 'Check this address' }).click()
  await expect(page.locator('.sp-address-pass').getByText('Mainnet', { exact: true })).toBeVisible()
  await page.getByLabel('Public Silent Payments address', { exact: true }).fill('not an address')
  await page.getByRole('button', { name: 'Check this address' }).click()
  await expect(page.getByText('Something is wrong with this address')).toBeVisible()
  await page.getByRole('button', { name: 'Copy example link' }).click()
  const copied = await page.evaluate(() => navigator.clipboard.readText())
  expect(copied).not.toContain('address=')
  expect(copied).not.toContain(mainnet)
  expect(await page.evaluate(() => JSON.stringify(localStorage))).not.toContain(mainnet)
  await page.reload()
  await expect(page.getByLabel('Public Silent Payments address', { exact: true })).toHaveValue('')
})

test('changed controls and navigation discard delayed computations', async ({ page }) => {
  let release
  const gate = new Promise((resolve) => { release = resolve })
  await page.route('**/api/experiments/payment', async (route) => {
    const response = await route.fetch()
    await gate
    try { await route.fulfill({ response }) } catch { /* The browser aborted the superseded request. */ }
  })
  await page.goto('/?view=studio&tool=payment')
  await page.getByRole('button', { name: 'Make a payment' }).click()
  await page.getByText('Network & advanced settings', { exact: true }).click()
  await page.getByLabel('Network', { exact: true }).selectOption('mainnet')
  release()
  await expect(page.getByText('✓ Real result')).toHaveCount(0)
  await expect(page.getByText('Illustration · Make a payment to see real results')).toBeVisible()
  await page.getByRole('link', { name: 'Addresses', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Addresses')
})

test('offline preview never claims computation and retry runs the actual engine', async ({ page }) => {
  await page.route('**/api/experiments/payment', (route) => route.abort())
  await page.goto('/?view=studio&tool=payment')
  await page.getByRole('button', { name: 'Make a payment' }).click()
  await expect(page.getByRole('alert')).toContainText('engine is unavailable')
  await expect(page.getByText('Illustration · Make a payment to see real results')).toBeVisible()
  await page.unroute('**/api/experiments/payment')
  await page.getByRole('button', { name: 'Retry', exact: true }).click()
  await expect(page.getByText('✓ Real result')).toBeVisible()
})

for (const [locale, dark] of [['en', false], ['it', true]]) {
  test(`studio fits 320px in ${locale} with keyboard and reduced motion`, async ({ page }) => {
    await page.setViewportSize({ width: 320, height: 900 })
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.addInitScript(({ locale, dark }) => { localStorage.setItem('sp-locale', locale); localStorage.setItem('theme', dark ? 'dark' : 'light') }, { locale, dark })
    await page.goto('/?view=studio&tool=payment&preset=mutation')
    const run = page.getByRole('button', { name: locale === 'en' ? 'Make a payment' : 'Crea un pagamento', exact: true })
    await run.focus(); await page.keyboard.press('Enter')
    await expect(page.getByText(locale === 'en' ? '✓ Real result' : '✓ Risultato reale')).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.getByText(locale === 'en' ? 'Inspect details' : 'Esamina i dettagli', { exact: true }).click()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  })
}
