import { test, expect } from '@playwright/test'

test('labeled destinations keep the scan key and change discovery when a label is omitted', async ({ page }) => {
  await page.goto('/?view=studio&tool=labels')
  await page.getByRole('button', { name: 'Derive and scan', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Payments found: 1 / 1' })).toBeVisible()
  await expect(page.getByText('Same scan key · Different labeled spend keys')).toBeVisible()
  await page.getByRole('checkbox', { name: 'Donations', exact: true }).uncheck()
  await expect(page.getByText('✓ Computed by the protocol engine')).toHaveCount(0)
  await page.getByRole('button', { name: 'Derive and scan', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Payments found: 0 / 1' })).toBeVisible()
  await page.getByLabel('Destination label', { exact: true }).selectOption('3')
  await page.getByRole('button', { name: 'Derive and scan', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Payments found: 1 / 1' })).toBeVisible()
  await page.getByRole('link', { name: 'Scanning →', exact: true }).click()
  await page.getByRole('button', { name: 'Run experiment', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Payments found: 2', exact: true })).toBeVisible()
  await expect(page.getByTestId('transaction-base')).toContainText('Payment found')
  await expect(page.getByTestId('transaction-labeled')).toContainText('Payment found')
  await expect(page.getByTestId('transaction-unrelated')).toContainText('Scanned · no match')
  await expect(page.getByTestId('transaction-no_inputs')).toContainText('Skipped')
  await expect(page.getByTestId('transaction-future_witness')).toContainText('Skipped')
  await expect(page.getByTestId('transaction-malformed_witness')).toContainText('Operation rejected')
  await page.getByRole('checkbox', { name: 'Donations', exact: true }).uncheck()
  await page.getByRole('button', { name: 'Run experiment', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Payments found: 1', exact: true })).toBeVisible()
  await expect(page.getByTestId('transaction-labeled')).toContainText('Scanned · no match')
  await page.getByRole('button', { name: 'Reset', exact: true }).click()
  await expect(page.getByTestId('transaction-base')).toHaveCount(0)
  await expect(page.getByRole('checkbox', { name: 'Donations', exact: true })).toBeChecked()
})

for (const [tool, locale, dark] of [['labels', 'en', false], ['scan', 'it', true]]) {
  test(`${tool} works on 320px in ${locale} with keyboard controls`, async ({ page }) => {
    await page.setViewportSize({ width: 320, height: 900 })
    await page.addInitScript(({ locale, dark }) => { localStorage.setItem('sp-locale', locale); localStorage.setItem('theme', dark ? 'dark' : 'light') }, { locale, dark })
    await page.goto(`/?view=studio&tool=${tool}`)
    await page.getByLabel(locale === 'en' ? 'Network' : 'Rete', { exact: true }).selectOption('mainnet')
    const button = page.getByRole('button', { name: tool === 'labels' ? 'Derive and scan' : 'Esegui esperimento', exact: true })
    await button.focus(); await page.keyboard.press('Enter')
    await expect(page.getByText(locale === 'en' ? '✓ Computed by the protocol engine' : '✓ Calcolato dal motore del protocollo')).toBeVisible()
    await expect(page.getByText(locale === 'en' ? '✓ Computed by the protocol engine' : '✓ Calcolato dal motore del protocollo')).toBeFocused()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.getByRole('button', { name: locale === 'en' ? 'Copy example link' : 'Copia link all’esempio' }).click()
    const copied = await page.evaluate(() => navigator.clipboard.readText())
    expect(Object.keys(Object.fromEntries(new URL(copied).searchParams)).sort()).toEqual(['preset','tool','view'])
  })
}
