import { test, expect } from '@playwright/test'

const selection = (id = 0, direction = 'send', subcase = 0) => `/?campaign=workshop&view=reference&case=${id}&direction=${direction}&subcase=${subcase}`

test('reference links select without execution, copy safely, and clear on home navigation', async ({ page }) => {
  const executions = []
  page.on('request', (request) => { if (request.url().includes('/api/single_test/')) executions.push(request.url()) })
  await page.goto(selection(18, 'receive', 1))
  await expect(page.getByLabel('Reference case', { exact: true })).toHaveValue('18')
  await expect(page.getByLabel('Subcase', { exact: true })).toHaveValue('1')
  await expect(page.getByRole('heading', { name: 'Silent Payments for sender change' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Run reference check' })).toBeEnabled()
  expect(executions).toEqual([])
  await page.getByText('Technical details', { exact: true }).click()
  await expect(page.getByRole('link', { name: 'Pinned BIP-352 source' })).toHaveAttribute('href', /c2ac36f48f71615984087fd151f410457edfed72/)
  await page.getByText('Technical details', { exact: true }).click()
  await page.getByRole('button', { name: 'Copy example link' }).click()
  const copied = await page.evaluate(() => navigator.clipboard.readText())
  expect(new URL(copied).search).toBe(new URL(page.url()).search)
  expect([...new URL(copied).searchParams.keys()].sort()).toEqual(['campaign', 'case', 'direction', 'subcase', 'view'])
  await page.getByRole('button', { name: 'Run reference check' }).click()
  await expect(page.getByTestId('reference-result').getByRole('status')).toHaveText('Matches reference')
  await expect(page.getByTestId('output-comparison')).not.toHaveCount(0)
  await page.getByRole('link', { name: 'Back to home', exact: false }).click()
  expect(new URL(page.url()).search).toBe('?campaign=workshop')
  await page.getByRole('link', { name: /^Guided demo/ }).click()
  await expect(page.getByRole('button', { name: 'Continue', exact: true })).toBeVisible()
})

test('invalid links fall back visibly and successful empty results differ from rejection', async ({ page }) => {
  await page.goto('/?view=reference&case=999&direction=receive&subcase=-1')
  await expect(page.getByRole('alert')).toContainText('example link is invalid')
  await expect(page.getByLabel('Reference case', { exact: true })).toHaveValue('0')
  await page.getByLabel('Reference case', { exact: true }).selectOption('24')
  await page.getByRole('button', { name: 'Run reference check' }).click()
  await expect(page.getByTestId('reference-result')).toContainText('Successful empty result')
  await page.getByLabel('Reference case', { exact: true }).selectOption('25')
  await page.getByRole('button', { name: 'Run reference check' }).click()
  await expect(page.getByTestId('reference-result').getByRole('status')).toHaveText('Expected rejection')
  await expect(page.getByTestId('reference-result')).not.toContainText('Successful empty result')
  await page.getByLabel('Direction', { exact: true }).selectOption('receive')
  await page.getByRole('button', { name: 'Run reference check' }).click()
  await expect(page.getByTestId('reference-result')).toContainText('Successful empty result')
})

test('recipient-limit receiving paginates every output and shows signature evidence', async ({ page }) => {
  await page.goto(selection(27, 'receive'))
  const response = page.waitForResponse((value) => value.url().includes('/api/single_test/receive/27'))
  await page.getByRole('button', { name: 'Run reference check' }).click()
  const result = await (await response).json()
  expect(result.outputs).toHaveLength(2323)
  await expect(page.getByTestId('reference-result').getByRole('status')).toHaveText('Matches reference')
  await expect(page.getByTestId('output-comparison')).toHaveCount(50)
  await expect(page.getByText('Page 1 of 47', { exact: true })).toBeVisible()
  const first = page.getByTestId('output-comparison').first()
  await first.getByText('Generated signature evidence', { exact: true }).click()
  await expect(first).toContainText(result.outputs[0].signature)
  await page.getByRole('button', { name: 'Next page' }).click()
  await expect(page.getByText('Page 2 of 47', { exact: true })).toBeVisible()
  await expect(page.getByTestId('output-comparison').first()).toContainText(result.outputs[50].pub_key)
  await page.getByText('Complete raw JSON', { exact: true }).click()
  await expect(page.getByTestId('reference-result').locator('pre')).toContainText(result.outputs[2322].pub_key)
})

test('selection changes and leaving discard delayed reference responses', async ({ page }) => {
  let release
  const gate = new Promise((resolve) => { release = resolve })
  let received
  const started = new Promise((resolve) => { received = resolve })
  await page.route('**/api/single_test/send/0?*', async (route) => {
    const response = await route.fetch()
    received()
    await gate
    await route.fulfill({ response }).catch(() => {})
  })
  await page.goto(selection())
  await page.getByRole('button', { name: 'Run reference check' }).click()
  await started
  await page.getByLabel('Reference case', { exact: true }).selectOption('25')
  release()
  await expect(page.getByRole('button', { name: 'Run reference check' })).toBeEnabled()
  await expect(page.getByTestId('reference-result')).toHaveCount(0)
  await page.getByRole('link', { name: 'Back to home', exact: false }).click()
  await page.getByRole('link', { name: /^Guided demo/ }).click()
  await page.getByRole('link', { name: 'All reference cases', exact: true }).click()
  await expect(page.getByTestId('reference-result')).toHaveCount(0)
})

test('request errors and mismatches stay distinct', async ({ page }) => {
  await page.route('**/api/single_test/send/0?*', (route) => route.fulfill({ status: 503, json: { error: 'Try again', code: 'UNAVAILABLE' } }))
  await page.goto(selection())
  await page.getByRole('button', { name: 'Run reference check' }).click()
  await expect(page.getByRole('alert')).toHaveText('Request error: Try again')
  await expect(page.getByTestId('reference-result')).toHaveCount(0)
  await page.unroute('**/api/single_test/send/0?*')
  await page.route('**/api/single_test/send/0?*', (route) => route.fulfill({ json: { test_passed: false, outputs: ['extra'], expected_outputs: ['missing'] } }))
  await page.getByRole('button', { name: 'Run reference check' }).click()
  await expect(page.getByTestId('reference-result').getByRole('status')).toHaveText('Unexpected mismatch')
  await expect(page.getByTestId('output-comparison')).toHaveCount(2)
})

test('Italian and dark theme remain readable on a narrow screen with keyboard controls', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.addInitScript(() => { localStorage.setItem('sp-locale', 'it'); localStorage.setItem('theme', 'dark') })
  await page.goto(selection())
  await expect(page.getByRole('heading', { name: 'Due input, un pagamento' })).toBeVisible()
  await expect(page.getByText('Perché è importante', { exact: false })).toBeVisible()
  await page.getByLabel('Scegli un esempio', { exact: true }).click()
  const select = page.getByLabel('Direzione', { exact: true })
  await select.focus()
  await select.press('ArrowDown')
  await select.press('Enter')
  await expect(select).toHaveValue('receive')
  await page.getByRole('button', { name: 'Verifica il riferimento' }).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByTestId('reference-result').getByRole('status')).toHaveText('Corrisponde al riferimento')
  expect(await page.getByRole('main').evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true)
})
